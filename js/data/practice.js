window.makeDrill = function(){
  const rnd = a => a[Math.floor(Math.random() * a.length)];
  function mc(correct, deltas, fmt){
    const set = new Set([fmt(correct)]);
    deltas.map(d => fmt(+(correct + d).toFixed(2))).forEach(p => { if(!set.has(p)) set.add(p); });
    let arr = [...set].slice(0, 4);
    while(arr.length < 4){ const fake = fmt(+(correct + (Math.random()*8-4)).toFixed(2)); if(!set.has(fake)){ set.add(fake); arr.push(fake); } }
    arr.sort(() => Math.random() - .5);
    return { opts: arr, a: arr.indexOf(fmt(correct)) };
  }
  const asNum = Math.random() < 0.6;   /* 60% 数值填空，40% 选择 */
  const kind = Math.floor(Math.random() * 4);
  if(kind === 0){
    const r = [4, 5, 6, 8, 9, 12][Math.floor(Math.random()*6)];
    const y = Math.round(72 / r);
    if(asNum) return { t:"num", q:`按 72 法则：年化收益约 ${r}%，资金翻倍大约需要几年？（填数字）`, ans:y, tol:0.6, unit:"年",
      why:`72 ÷ ${r} ≈ ${y} 年。心算复利与通胀腰斩年限都用它。` };
    const o = mc(y, [-2, -1, 1, 2, 3], v => v + " 年");
    return { t:"mc", q:`按 72 法则：年化收益约 ${r}%，资金翻倍大约需要几年？`, opts:o.opts, a:o.a,
      why:`72 ÷ ${r} ≈ ${y} 年。` };
  }
  if(kind === 1){
    const d = [10, 15, 20, 25, 33, 50][Math.floor(Math.random()*6)];
    const need = Math.round(100 / (100 - d) * 100);
    if(asNum) return { t:"num", q:`某持仓亏损 ${d}%，需要上涨约多少百分比才能回本？（填数字，如 25 表示 25%）`, ans:need, tol:1, unit:"%",
      why:`回本涨幅 = 100/(100−${d}) − 1 ≈ ${need}%。亏损与回本不对称，正是深亏毁掉复利的原因。` };
    const o = mc(need, [-25, -15, -8, 10, 20, 35], v => v + "%");
    return { t:"mc", q:`某持仓亏损 ${d}%，需要上涨约多少才能回本？`, opts:o.opts, a:o.a,
      why:`回本涨幅 ≈ ${need}%。` };
  }
  if(kind === 2){
    const cap = [10, 20, 30, 50][Math.floor(Math.random()*4)];
    const stop = [4, 5, 8, 10][Math.floor(Math.random()*4)];
    const pos = +(cap * 0.02 / (stop/100)).toFixed(1);
    if(asNum) return { t:"num", q:`总资金 ${cap} 万，单笔风险上限 2%，止损距离 ${stop}%。最大仓位约多少万元？（填数字，容差 ±0.2）`, ans:pos, tol:0.2, unit:"万",
      why:`允许亏损 ${cap}×2% = ${(cap*0.02).toFixed(1)} 万 ÷ 止损 ${stop}% ≈ 仓位 ${pos} 万。仓位由风险预算反推，而非感觉。` };
    const o = mc(pos, [-pos*0.4, -pos*0.2, pos*0.2, pos*0.4].map(v=>+v.toFixed(1)), v => v + " 万");
    return { t:"mc", q:`总资金 ${cap} 万，单笔风险上限 2%，止损距离 ${stop}%。最大仓位约为多少万元？`, opts:o.opts, a:o.a,
      why:`风险预算 ÷ 止损距离 = 仓位。` };
  }
  const entry = 10, risk = [0.4, 0.5, 0.8, 1][Math.floor(Math.random()*4)];
  const k = [1, 1.5, 2, 3][Math.floor(Math.random()*4)];
  const sl = +(entry - risk).toFixed(2), tp = +(entry + risk * k).toFixed(2);
  if(asNum) return { t:"num", q:`入场价 ${entry}，止损 ${sl}，目标 ${tp}。盈亏比是多少？（填数字，如 2.5 表示 2.5:1）`, ans:+k.toFixed(1), tol:0.1, unit:":1",
    why:`盈利空间 ${risk} ÷ 风险空间 ${risk} = ${k}:1。盈亏比 ≥ 2:1 时，胜率超过 1/3 就是正期望。` };
  const o = mc(k, [-1.5, -1, -0.5, 0.5, 1, 1.5], v => v + " : 1");
  return { t:"mc", q:`入场价 ${entry}，止损 ${sl}，目标 ${tp}。这笔交易的盈亏比是？`, opts:o.opts, a:o.a,
    why:`盈利空间 ÷ 风险空间 = ${k}:1。` };
};

